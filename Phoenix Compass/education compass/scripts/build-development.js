const fs = require('fs')
const path = require('path')
const {
  buildArtifactAtomically,
  copyTree,
  DIST_ROOT,
  normalizeArtifactProjectConfig,
  RELEASE_VERSION,
  validateMiniProgramArtifactBoundary,
  validateReleaseOutput
} = require('./build-release')

const SOURCE_ROOT = path.resolve(__dirname, '..')
const DEFAULT_API_BASE_URL = 'http://127.0.0.1:3000'
const ROOT_FILES = ['app.js', 'app.json', 'app.wxss', 'project.config.json', 'sitemap.json']
const ROOT_DIRECTORIES = ['assets', 'components', 'config', 'models', 'pages', 'services', 'utils']

function invariant(condition, message) {
  if (!condition) throw new Error(message)
}

function validateDevelopmentApiBaseUrl(value) {
  invariant(typeof value === 'string' && value === value.trim(),
    'PHOENIX_DEVELOPMENT_API_BASE_URL must not contain surrounding whitespace')
  let parsed
  try {
    parsed = new URL(value)
  } catch {
    throw new Error('PHOENIX_DEVELOPMENT_API_BASE_URL must be a valid loopback URL')
  }
  invariant(parsed.protocol === 'http:' && parsed.hostname === '127.0.0.1',
    'PHOENIX_DEVELOPMENT_API_BASE_URL must use http://127.0.0.1')
  invariant(!parsed.username && !parsed.password && !parsed.search && !parsed.hash,
    'PHOENIX_DEVELOPMENT_API_BASE_URL must not contain credentials, a query, or a fragment')
  invariant(parsed.pathname === '/',
    'PHOENIX_DEVELOPMENT_API_BASE_URL must be an origin without a path')
  invariant(Boolean(parsed.port) && Number(parsed.port) >= 1 && Number(parsed.port) <= 65535,
    'PHOENIX_DEVELOPMENT_API_BASE_URL must include a valid port')
  return parsed.origin
}

function developmentRuntime(apiBaseUrl) {
  return `// Generated by scripts/build-development.js. Do not hand-edit.\nconst API_BASE_URL = ${JSON.stringify(apiBaseUrl)}\n\nfunction accountEnvironment() {\n  if (typeof wx === 'undefined') return 'test'\n  if (!wx.getAccountInfoSync) return 'unknown'\n  try {\n    const info = wx.getAccountInfoSync()\n    const value = info && info.miniProgram && info.miniProgram.envVersion\n    return ['develop', 'trial', 'release'].includes(value) ? value : 'unknown'\n  } catch (error) {\n    return 'unknown'\n  }\n}\n\nfunction allowsDevelopmentLoopbackHttp(value) {\n  return accountEnvironment() === 'develop' && value === API_BASE_URL\n}\n\nfunction mode() { return 'remote' }\nfunction apiBaseUrl() {\n  if (!allowsDevelopmentLoopbackHttp(API_BASE_URL)) {\n    const error = new Error('本机联调包仅允许在 develop 环境使用')\n    error.code = 'DEVELOPMENT_BUILD_ENVIRONMENT_REQUIRED'\n    throw error\n  }\n  return API_BASE_URL\n}\n\nmodule.exports = { API_BASE_URL, accountEnvironment, allowsDevelopmentLoopbackHttp, apiBaseUrl, mode, isDemo: () => false }\n`
}

function buildDevelopment(options = {}) {
  const apiBaseUrl = validateDevelopmentApiBaseUrl(
    options.apiBaseUrl || process.env.PHOENIX_DEVELOPMENT_API_BASE_URL || DEFAULT_API_BASE_URL
  )
  const outputDirectory = path.resolve(options.outputDirectory || path.join(DIST_ROOT, 'development'))
  validateReleaseOutput(outputDirectory)

  return buildArtifactAtomically(outputDirectory, (stagingDirectory) => {
    for (const name of ROOT_FILES) copyTree(
      path.join(SOURCE_ROOT, name), path.join(stagingDirectory, name), name
    )
    for (const name of ROOT_DIRECTORIES) copyTree(
      path.join(SOURCE_ROOT, name), path.join(stagingDirectory, name), name
    )

    const appConfigPath = path.join(stagingDirectory, 'app.json')
    const appConfig = JSON.parse(fs.readFileSync(appConfigPath, 'utf8'))
    const sourcePageCount = appConfig.pages.length
    appConfig.pages = appConfig.pages.filter((page) => !page.startsWith('pages/admin-'))
    for (const page of [
      'pages/agent-chat/index',
      'pages/assessment-analysis/index',
      'pages/compass/index',
      'pages/compass-questionnaire/index',
      'pages/compass-preview/index'
    ]) invariant(appConfig.pages.includes(page), `development build must include ${page}`)
    fs.writeFileSync(appConfigPath, `${JSON.stringify(appConfig, null, 2)}\n`)

    const projectConfigPath = path.join(stagingDirectory, 'project.config.json')
    const projectConfig = JSON.parse(fs.readFileSync(projectConfigPath, 'utf8'))
    normalizeArtifactProjectConfig(projectConfig)
    projectConfig.description = `LOCAL DEVTOOLS LOOPBACK ONLY - Phoenix Family OS V${RELEASE_VERSION}`
    projectConfig.projectname = `Phoenix-Family-OS-V${RELEASE_VERSION}-Local-DevTools`
    projectConfig.packOptions = { ignore: [], include: [] }
    projectConfig.setting = { ...projectConfig.setting, urlCheck: false }
    fs.writeFileSync(projectConfigPath, `${JSON.stringify(projectConfig, null, 2)}\n`)

    fs.writeFileSync(path.join(stagingDirectory, 'config', 'runtime.js'), developmentRuntime(apiBaseUrl))
    fs.writeFileSync(path.join(stagingDirectory, 'services', 'demo-runtime.js'),
      '// Local DevTools remote build: demo data is intentionally absent.\nmodule.exports = { repository: Object.freeze({}), aiProvider: Object.freeze({}) }\n')
    fs.writeFileSync(path.join(stagingDirectory, 'DEVELOPMENT_BUILD.json'), `${JSON.stringify({
      schemaVersion: 1,
      productVersion: RELEASE_VERSION,
      generatedAt: new Date().toISOString(),
      artifactClass: 'LOCAL_DEVTOOLS_LOOPBACK_ONLY',
      runtimeMode: 'remote',
      uploadAuthorized: false,
      deviceTestingSupported: false,
      apiOrigin: apiBaseUrl,
      sourcePageCount,
      developmentPageCount: appConfig.pages.length,
      excludesLocalDatabase: true,
      excludesDemoReportGenerator: true,
      excludesServerSource: true
    }, null, 2)}\n`)

    validateMiniProgramArtifactBoundary(stagingDirectory, 'DEVELOPMENT_BUILD.json')
  })
}

if (require.main === module) {
  const output = buildDevelopment()
  console.log(`LOCAL_DEVTOOLS_LOOPBACK_ONLY build created: ${output}`)
}

module.exports = {
  buildDevelopment,
  DEFAULT_API_BASE_URL,
  developmentRuntime,
  validateDevelopmentApiBaseUrl
}
